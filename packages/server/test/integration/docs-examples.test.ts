// docs/examples.md shows what an assistant does with the server: a prompt, the tool calls and their
// results, produced by running the real server against the fake TradingView app of the test suite
// (a synthetic NASDAQ:AAPL chart). The page is generated by `pnpm docs:examples`, and these tests
// fail when it has fallen behind the tools, or when the README quotes something the page does not
// say.

// Nothing in this file may run a real program or start TradingView.
vi.mock('node:child_process', () => ({
  spawn: () => {
    throw new Error('A test tried to start a real program with spawn');
  },
  execFile: () => {
    throw new Error('A test tried to start a real program with execFile');
  },
}));

const README_PATH = new URL('../../../../README.md', import.meta.url);

// The files as the repository stores them, whatever line endings a checkout gave them.
function readText(path: string | URL): string {
  return readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
}

let runs: ScenarioRun[];
let page: string;

// All scenarios run against a fake app each, which takes a few seconds.
beforeAll(async () => {
  runs = await runScenarios();
  page = renderExamples(runs);
}, 120_000);

// Where two texts first differ, for a message that does not print a whole page.
function firstDifference(committed: string, generated: string): string {
  const committedLines = committed.split('\n');
  const generatedLines = generated.split('\n');
  const count = Math.max(committedLines.length, generatedLines.length);
  for (let index = 0; index < count; index += 1) {
    if (committedLines[index] !== generatedLines[index]) {
      return (
        `First difference at line ${String(index + 1)}:\n` +
        `  committed: ${committedLines[index] ?? '(the file ends)'}\n` +
        `  generated: ${generatedLines[index] ?? '(the page ends)'}`
      );
    }
  }
  return 'The texts differ.';
}

describe('docs/examples.md', () => {
  test('docs/examples.md is up to date', () => {
    let committed: string;
    try {
      committed = readText(EXAMPLES_PATH);
    } catch {
      throw new Error(
        'docs/examples.md does not exist. Run `pnpm docs:examples` to generate it, then commit it.',
      );
    }

    if (committed !== page) {
      throw new Error(
        'docs/examples.md is out of date. Run `pnpm docs:examples` and commit the result.\n' +
          firstDifference(committed, page),
      );
    }
  });

  test('the page shows no duration and no time that the clock gave', () => {
    // The key of the duration would be in quotes in a result; the note mentions it without.
    expect(page).not.toContain('"durationMs"');
    // The compile time is fixed to the time of the last bar of the fake chart.
    expect(page).toContain('"compiledAt": 1729987200');
    expect(page).toContain('"compiledAtIso": "2024-10-27T00:00:00Z"');
    // So is the moment an alert set without an expiration is set at: it expires the default span
    // of TradingView after it, 30 days on the free plan of the fake app.
    expect(page).toContain('"expiration": 1732579200');
    expect(page).toContain('"expirationIso": "2024-11-26T00:00:00Z"');
  });

  test('the page does not depend on the clock', async () => {
    // Two values of a result come from the clock: the compile time, which the server stamps when
    // it compiles, and the expiration of an alert set without one, which it sets from the time of
    // the call.
    vi.useFakeTimers({ toFake: ['Date'] });
    try {
      vi.setSystemTime(new Date('2031-05-17T03:21:09Z'));

      expect(renderExamples(await runScenarios())).toBe(page);
    } finally {
      vi.useRealTimers();
    }
  }, 120_000);

  test('the scenarios cover the tool families, in the order of the page', () => {
    expect(SCENARIOS.map(({ steps }) => steps.map(({ tool }) => tool))).toEqual([
      ['chart_get_state'],
      ['chart_set_symbol', 'chart_set_timeframe'],
      ['data_get_ohlcv'],
      ['indicator_list', 'indicator_get_values'],
      ['indicator_search', 'indicator_add'],
      ['pine_new', 'pine_compile'],
      ['pine_smart_compile'],
      ['strategy_get_results', 'strategy_get_trades'],
      ['drawing_create', 'drawing_list'],
      ['alert_create'],
      ['alert_create', 'alert_list'],
      ['watchlist_add_bulk'],
      ['replay_start', 'replay_step', 'replay_status', 'replay_stop'],
      ['screenshot_capture'],
    ]);
  });

  // The run of the scenario whose steps are `tools`.
  function runOf(...tools: string[]): ScenarioRun {
    const run = runs.find(
      ({ scenario }) =>
        scenario.steps.every(({ tool }, index) => tool === tools[index]) &&
        scenario.steps.length === tools.length,
    );
    if (run === undefined) {
      throw new Error(`No scenario has the steps ${tools.join(', ')}`);
    }
    return run;
  }

  test('the scenario of the support line shows the new line in the list, as drawn by this session', () => {
    const { results } = runOf('drawing_create', 'drawing_list');

    expect(results[0]).toMatchObject({ ok: true, data: { shape: 'horizontal_line' } });
    const id = results[0]?.ok === true ? (results[0].data as { id: string }).id : '';
    expect(results[1]).toMatchObject({
      ok: true,
      data: {
        drawings: expect.arrayContaining([
          expect.objectContaining({ id, text: 'Support', createdByServer: true }),
        ]) as unknown,
      },
    });
  });

  test('the alert is created on a plan with room, and refused with PLAN_LIMIT on a full one, whose alerts are listed', () => {
    const created = runOf('alert_create');
    const refused = runOf('alert_create', 'alert_list');

    // One request for both: only the plan differs.
    expect(refused.scenario.prompt).toBe(created.scenario.prompt);
    expect(created.results[0]).toMatchObject({ ok: true, data: { condition: 'crossing' } });
    expect(refused.results[0]).toMatchObject({
      ok: false,
      error: { code: 'PLAN_LIMIT', details: { feature: 'SERVER_SIDE_ALERTS', limit: 3 } },
    });
    expect(refused.results[1]).toMatchObject({
      ok: true,
      data: {
        alerts: [
          { status: 'active', createdByServer: false },
          { status: 'active', createdByServer: false },
          { status: 'active', createdByServer: false },
        ],
      },
    });
  });

  test('the scenario of the watchlist shows what came of each symbol', () => {
    const [result] = runOf('watchlist_add_bulk').results;

    expect(result).toMatchObject({
      ok: true,
      data: {
        added: ['NYSE:IBM', 'FX:EURUSD'],
        skipped: [
          { symbol: 'NASDAQ:MSFT', reason: 'already_listed' },
          { symbol: 'NASDAQ:MSTF', reason: 'unknown' },
        ],
      },
    });
  });

  test('the replay practice session leaves replay at the end and trades nothing', () => {
    const { results } = runOf('replay_start', 'replay_step', 'replay_status', 'replay_stop');

    expect(results.map((result) => result.ok)).toEqual([true, true, true, true]);
    // The paper trading of replay holds nothing: no tool trades.
    expect(results[2]).toMatchObject({
      data: { active: true, position: null, realizedPL: null },
    });
    expect(results[3]).toMatchObject({ data: { active: false } });
  });

  test('the scenario of the screenshot shows a note in place of the image', () => {
    const { results } = runOf('screenshot_capture');
    const section = page.split(/^## /m).find((text) => text.includes('`screenshot_capture`'));

    // The result holds the image, as MCP image content in front of the JSON block.
    expect(results[0]).toMatchObject({
      ok: true,
      images: ['image/jpeg'],
      data: { target: 'chart', format: 'jpeg' },
    });
    // The page names it in a note above the JSON block, and holds none of its data: a jpeg in
    // base64 starts with /9j/, a png with iVBORw0KGgo.
    expect(section).toMatch(
      /\*\*The server returns\*\*\n\n_The image itself, of type image\/jpeg, [^\n]*_\n\n```json\n/,
    );
    expect(page).not.toMatch(/\/9j\/[\w+/]{8}|iVBORw0KGgo/);
  });

  test('the screenshots of the page are jpegs, whose size the fake app sets byte by byte', () => {
    // The fake app deflates a png with the zlib of Node, whose output can change with Node; a jpeg
    // it writes byte by byte: 140 bytes of headers around a scan of 2 bits for each block of 8 by 8
    // pixels, so 140 + 148 * 80 * 2 / 8 = 3100 bytes for the chart of 1180 by 640 pixels.
    const shots = SCENARIOS.flatMap(({ steps }) => steps).filter(
      ({ tool }) => tool === 'screenshot_capture',
    );
    expect(shots.length).toBeGreaterThan(0);
    for (const { arguments: args } of shots) {
      expect(args).toMatchObject({ format: 'jpeg' });
    }
    expect(runOf('screenshot_capture').results[0]).toMatchObject({
      data: { format: 'jpeg', width: 1180, height: 640, bytes: 3100 },
    });
  });

  test('the alerts that fill the plan expire within the span a new alert gets from the time of the page', () => {
    const { results } = runOf('alert_create', 'alert_list');
    // The page is set at the time of the last bar, 2024-10-27, and an alert set then without an
    // expiration expires on 2024-11-26 (the alert of the plan with room): alerts of the same plan
    // set before then expire between the two.
    const listed = results[1]?.ok === true ? results[1].data : null;
    const alerts = (listed as { alerts?: { expiration: number }[] } | null)?.alerts ?? [];

    expect(alerts).toHaveLength(3);
    for (const { expiration } of alerts) {
      expect(expiration).toBeGreaterThan(1729987200);
      expect(expiration).toBeLessThan(1732579200);
    }
  });

  test('the scenario of the full chart ends in the PLAN_LIMIT error and shows it', () => {
    const run = runs.find(({ scenario }) =>
      scenario.steps.some(({ tool }) => tool === 'indicator_add'),
    );

    expect(run?.results.at(-1)).toMatchObject({
      ok: false,
      error: { code: 'PLAN_LIMIT', details: { feature: 'INDICATORS_ON_CHART', limit: 2 } },
    });
    expect(page).toContain('"code": "PLAN_LIMIT"');
  });

  test('the scenario of smart compile shows its attempts and its diff', () => {
    const run = runs.find(({ scenario }) =>
      scenario.steps.some(({ tool }) => tool === 'pine_smart_compile'),
    );

    expect(run?.results[0]).toMatchObject({
      ok: true,
      data: { success: true, attempts: [{ applied: expect.any(Array) as string[] }, {}] },
    });
    expect(page).toContain('```diff\n@@ -1,3 +1,3 @@\n');
  });

  // The numbers a reader would take for facts: dates, decimals and whole numbers of three digits or
  // more. A summary may count in digits ("2 of 3 trades"), so smaller whole numbers are not checked.
  function claimsOf(summary: string): string[] {
    const plain = summary.replaceAll(/(?<=\d),(?=\d{3}\b)/g, '');
    return plain.match(/\d{4}-\d{2}-\d{2}|\d+\.\d+|\d{3,}/g) ?? [];
  }

  function shows(shown: string, claim: string): boolean {
    const escaped = claim.replaceAll('.', String.raw`\.`);
    return new RegExp(String.raw`(?<![\d.])${escaped}(?!\d|\.\d)`).test(shown);
  }

  test('each summary states only numbers and dates that the page shows before it', () => {
    // One section for each scenario, headed by its number and title. What it shows is everything
    // above the answer of the assistant, cut lists included.
    const sections = page.split(/^## /m).slice(1);
    expect(sections).toHaveLength(runs.length);

    for (const [index, { scenario }] of runs.entries()) {
      const shown = (sections[index] ?? '').split('**The assistant answers**')[0] ?? '';
      const invented = claimsOf(scenario.summary).filter((claim) => !shows(shown, claim));

      expect(invented, `${scenario.title}: the summary states what the page does not show`).toEqual(
        [],
      );
    }
  });

  test('the check for invented numbers finds a number that no result shows', () => {
    expect(claimsOf('It made 10,000 on 2024-10-27, up 1.55 percent, in 3 trades.')).toEqual([
      '10000',
      '2024-10-27',
      '1.55',
    ]);
    expect(shows('{"netProfit":155,"x":1.55}', '155')).toBe(true);
    expect(shows('{"netProfit":1555}', '155')).toBe(false);
    expect(shows('{"netProfit":155.5}', '155')).toBe(false);
    expect(shows('{"at":"2024-10-27T00:00:00Z"}', '2024-10-27')).toBe(true);
  });
});

describe('the README', () => {
  const readme = readText(README_PATH);

  // The text under a heading, up to the next heading of the same or a higher level.
  function sectionOf(heading: string): string {
    const level = /^#+/.exec(heading)?.[0].length ?? 0;
    const start = readme.indexOf(`\n${heading}\n`);
    expect(start, `README has no "${heading}" heading`).toBeGreaterThanOrEqual(0);
    const rest = readme.slice(start + heading.length + 2);
    const end = rest.search(new RegExp(`^#{1,${String(level)}} `, 'm'));
    return end === -1 ? rest : rest.slice(0, end);
  }

  // How GitHub turns the text of a heading into the anchor that links to it.
  function anchorOf(heading: string): string {
    return heading
      .toLowerCase()
      .replaceAll(/[^\p{L}\p{N}\s_-]/gu, '')
      .trim()
      .replaceAll(/\s/g, '-');
  }

  const tryThese = (): string => sectionOf('### Try these prompts');

  test('the README lists eleven prompts, each one a scenario of the page', () => {
    // A line break inside a paragraph is a space, whatever the width the README is wrapped to.
    const prompts = [...tryThese().matchAll(/\*\*"([^"]+)"\*\*/g)].map((match) =>
      (match[1] ?? '').replaceAll(/\s+/g, ' '),
    );

    expect(prompts).toHaveLength(11);
    for (const prompt of prompts) {
      expect(
        SCENARIOS.map((scenario) => scenario.prompt),
        `"${prompt}" is no scenario prompt`,
      ).toContain(prompt);
    }
    expect(new Set(prompts).size).toBe(11);
  });

  // The excerpts of results in the README, each as its lines without their indent and trailing
  // comma, where … marks lines left out between parts of a result.
  const excerptsOf = (): string[][] =>
    [...tryThese().matchAll(/```json\n([\s\S]*?)```/g)].map((match) =>
      (match[1] ?? '')
        .split('\n')
        .map((line) => line.trim().replace(/,$/, ''))
        .filter((line) => line !== ''),
    );
  const GAP = '…';

  test('each excerpt of a result in the README is two to four lines that the page shows', () => {
    const shownLines = new Set(page.split('\n').map((line) => line.trim().replace(/,$/, '')));
    const excerpts = excerptsOf();

    expect(excerpts).toHaveLength(11);
    for (const lines of excerpts) {
      const shown = lines.filter((line) => line !== GAP);
      expect(shown.length).toBeGreaterThanOrEqual(2);
      expect(shown.length).toBeLessThanOrEqual(4);
      for (const line of shown) {
        expect(shownLines.has(line), `The page has no line ${line}`).toBe(true);
      }
    }
  });

  test('an excerpt marks with … where its lines come from different parts of a result', () => {
    // The indents a line of the page has, by its text: lines at one indent are members of one
    // level of a result.
    const indents = new Map<string, Set<number>>();
    for (const line of page.split('\n')) {
      const text = line.trim().replace(/,$/, '');
      indents.set(
        text,
        (indents.get(text) ?? new Set()).add(line.length - line.trimStart().length),
      );
    }
    const sameLevel = (a: string, b: string): boolean =>
      [...(indents.get(a) ?? [])].some((indent) => indents.get(b)?.has(indent) === true);

    for (const lines of excerptsOf()) {
      lines.forEach((line, index) => {
        const next = lines[index + 1];
        if (line !== GAP && next !== undefined && next !== GAP) {
          expect(sameLevel(line, next), `${line} and ${next} need ${GAP} between them`).toBe(true);
        }
      });
    }
  });

  test('the README says what the page leaves out of the results', () => {
    const intro = tryThese().split('**"')[0] ?? '';

    expect(intro).not.toMatch(/full results/);
    expect(intro).toMatch(/durationMs/);
    expect(intro).toMatch(/cut/);
  });

  test('the README says which scripts need confirm for a new version, and how --tools and a profile combine', () => {
    // A line break inside a paragraph is a space.
    const safety = sectionOf('### Safety').replaceAll(/\s+/g, ' ');
    const profiles = sectionOf('### Tool profiles').replaceAll(/\s+/g, ' ');

    expect(safety).toMatch(/script that this session (?:of the server )?did not create/);
    expect(profiles).toMatch(/--tools[\s\S]*narrow/);
    expect(profiles).toMatch(/--profile core --tools 'pine_\*'/);
  });

  test('the README says that no tool trades, and which objects of the user need confirm', () => {
    const safety = sectionOf('### Safety').replaceAll(/\s+/g, ' ');

    expect(safety).toMatch(/No tool places orders/);
    expect(safety).toMatch(/drawing, alert, watchlist symbol or tab that this session did not/);
  });

  test('the README states how many tools each profile offers, as the registry counts them', () => {
    const profiles = sectionOf('### Tool profiles').replaceAll(/\s+/g, ' ');
    const count = (profile: Profile): string =>
      String(selectTools(allTools, { profile, patterns: [] }).length);

    expect(profiles).toContain(`all its ${count('full')} tools (\`--profile full\`)`);
    expect(profiles).toContain(`a reduced set of ${count('core')} essential tools`);
    expect(profiles).toContain(`only the ${count('readonly')} tools that read`);
  });

  test('each link of the README into the page leads to a section of it', () => {
    const anchors = new Set(
      [...page.matchAll(/^## (.*)$/gm)].map((match) => anchorOf(match[1] ?? '')),
    );
    const links = [...readme.matchAll(/\]\(docs\/examples\.md#([^)]+)\)/g)].map(
      (match) => match[1] ?? '',
    );

    expect(links.length).toBeGreaterThanOrEqual(11);
    for (const link of links) {
      expect(anchors.has(link), `The page has no section ${link}`).toBe(true);
    }
  });

  test('the README names the prompts that the server offers', async () => {
    const { server } = createMcpServer(testConfig(), {
      launcher: refusingLauncher(),
      logger: quietLogger,
    });
    const client = await connectInMemoryClient(server);
    try {
      const { prompts } = await client.listPrompts();

      expect(prompts.map(({ name }) => name).sort()).toEqual([
        'analyze_current_chart',
        'debug_pine_script',
        'multi_timeframe_review',
        'replay_practice_session',
        'write_and_backtest_strategy',
      ]);
      for (const { name } of prompts) {
        expect(readme, `The README does not name the prompt ${name}`).toContain(`\`${name}\``);
      }
      // The README counts them in words, in its introduction and where it lists them. A line
      // break inside a paragraph, quoted or not, is a space.
      const count = ['no', 'one', 'two', 'three', 'four', 'five', 'six', 'seven'][prompts.length];
      const prose = readme.replaceAll(/\n>? */g, ' ');
      expect(prose).toContain(`and ${String(count)} prompts for common jobs`);
      expect(prose).toContain(`The server also offers ${String(count)} prompts of its own`);
    } finally {
      await client.close();
      await server.close();
    }
  });
});
